// ─── Lookup Maps ───

const _bySlug = new Map<string, CanonicalExercise>();
CANONICAL_EXERCISES.forEach(e => _bySlug.set(e.slug, e));

/** Get canonical exercise by slug (hyphenated). */
export function getCanonicalExercise(slug: string): CanonicalExercise | undefined {
  const normalized = slug.toLowerCase().replace(/_/g, "-");
  return _bySlug.get(normalized) || _bySlug.get(slug);
}

