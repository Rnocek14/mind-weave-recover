// ─── Core Types ───

export interface CanonicalExercise {
  /** Hyphenated slug used in URLs and exercise_events */
  slug: string;
  /** Display title */
  title: string;
  /** Lucide icon component */
  icon: LucideIcon;
  /** UI category for grouping */
  category: string;
  /** Estimated duration range */
  duration: string;
  /** General difficulty label */
  difficulty: "Easy" | "Medium" | "Hard";
  /** Tailwind gradient class */
  color: string;

  // ─── Engine metadata ───
  /** Lesson-engine domains for scoring */
  engineDomains: string[];
  /** Base minutes for lesson planning */
  baseMinutes: number;
  /** Component family to prevent back-to-back same-UI games */
  baseComponent: string;

  // ─── Clinical metadata ───
  /** Primary recovery domain */
  recoveryDomain: string;
  /** Cognitive sub-domains fed by this exercise */
  cognitiveDomains: string[];
  /** Whether exercise involves speech production */
  hasSpeechOutput: boolean;
  /** Clinical rationale */
  clinicalRationale: string;
  /** Outcome metrics contributed to */
  outcomeMetrics: string[];
  /** Expected functional gain */
  expectedGain: string;
  /** Focus area IDs this exercise targets */
  focusAreas: string[];
  /** What this supports in daily life */
  functionalMeaning: string;

  // ─── Gating ───
  /** Minimum capability scores to access. Undefined = no gating (always accessible) */
  gatingRequirements?: {
    vision?: number;
    motor?: number;
    attention?: number;
  };
  /** Reason if gated out */
  gatingReason?: string;
  /** Suggested alternative if gated */
  gatingAlternative?: string;
}

